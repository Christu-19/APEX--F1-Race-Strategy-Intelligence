def clean_race_results(df):

    cleaned_df = df.copy()

    cleaned_df = cleaned_df.drop(
        columns=[
            "BroadcastName",
            "TeamColor",
            "HeadshotUrl",
            "CountryCode",
            "Q1",
            "Q2",
            "Q3"
        ]
    )

    return cleaned_df

